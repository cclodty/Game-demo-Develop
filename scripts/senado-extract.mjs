// Pulls the part of the Largo do Senado model the game uses out of the Senado
// project (senado/ on the claude/practical-archimedes-ay1ycf branch).
//
//   node scripts/senado-extract.mjs <path to the senado folder>
//
// Writes:
//   src/senado/model.js   the Senado builder, copied unchanged
//   src/senado/data.js    senado_massing.json trimmed to the play strip + scenery margin
//   src/senado/assets.js  the paving and window textures as data URIs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SENADO, toData, toGame } from '../src/senado/transform.js';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/senado-extract.mjs <path to the senado folder>');
  process.exit(1);
}
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/senado');
const data = JSON.parse(fs.readFileSync(path.join(src, 'data/senado_massing.json'), 'utf8'));

// visual window in game space
const vx = SENADO.halfW + SENADO.keep;
const vz = SENADO.halfD + SENADO.keep;
const inView = ([x, y], pad = 0) => {
  const [X, Z] = toGame(x, y);
  return Math.abs(X) <= vx + pad && Math.abs(Z) <= vz + pad;
};
const boxInView = (ring) => {
  let x0 = Infinity;
  let x1 = -Infinity;
  let z0 = Infinity;
  let z1 = -Infinity;
  for (const p of ring) {
    const [X, Z] = toGame(p[0], p[1]);
    x0 = Math.min(x0, X);
    x1 = Math.max(x1, X);
    z0 = Math.min(z0, Z);
    z1 = Math.max(z1, Z);
  }
  return x1 >= -vx && x0 <= vx && z1 >= -vz && z0 <= vz;
};
const r2 = (v) => Math.round(v * 100) / 100;
const ring2 = (ring) => ring.map(([x, y]) => [r2(x), r2(y)]);
const poly2 = (p) => ({ ...p, outer: ring2(p.outer), holes: (p.holes || []).map(ring2) });

const buildings = data.buildings.filter((b) => boxInView(b.outer)).map(poly2);
const parts = data.parts.filter((b) => boxInView(b.outer)).map(poly2);
const roads = data.roads.filter((r) => r.pts.some((p) => inView(p, r.w))).map((r) => ({ ...r, pts: ring2(r.pts) }));
const green = data.green.filter((g) => boxInView(g.outer)).map(poly2);
const trees = data.trees.filter((t) => inView(t));

// ground plane: the data-space box around the visual window
const corners = [
  [-vx, -vz],
  [vx, -vz],
  [vx, vz],
  [-vx, vz],
].map(([X, Z]) => toData(X, Z));
const bounds = [
  Math.floor(Math.min(...corners.map((c) => c[0]))),
  Math.floor(Math.min(...corners.map((c) => c[1]))),
  Math.ceil(Math.max(...corners.map((c) => c[0]))),
  Math.ceil(Math.max(...corners.map((c) => c[1]))),
];

const trimmed = {
  ...data,
  meta: { ...data.meta, bounds, trimmedFor: 'Bullet Ballet', trim: SENADO },
  buildings,
  parts,
  roads,
  green,
  trees,
};
const header = `// Generated by scripts/senado-extract.mjs from senado/data/senado_massing.json.\n// Map data © OpenStreetMap contributors (ODbL). Do not edit by hand.\n`;
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'data.js'), `${header}export default ${JSON.stringify(trimmed)};\n`);

const model = fs.readFileSync(path.join(src, 'viewer/model.js'), 'utf8');
fs.writeFileSync(
  path.join(out, 'model.js'),
  `// Copied unchanged from senado/viewer/model.js by scripts/senado-extract.mjs.\n// Edit it in the Senado project and re-run the script.\n\n${model}`,
);

const png = (n) => `data:image/png;base64,${fs.readFileSync(path.join(src, 'viewer/assets', n)).toString('base64')}`;
fs.writeFileSync(
  path.join(out, 'assets.js'),
  `// Generated by scripts/senado-extract.mjs from senado/viewer/assets.\nexport const CALCADA = '${png('calcada_waves.png')}';\nexport const LOUVRE = '${png('louvre.png')}';\nexport const GLAZING = '${png('glazing.png')}';\nexport const FACADE = '${png('facade_generic.png')}';\n`,
);

const kb = (f) => (fs.statSync(path.join(out, f)).size / 1024).toFixed(0);
console.log(`buildings ${buildings.length}/${data.buildings.length}, parts ${parts.length}, roads ${roads.length}/${data.roads.length}, green ${green.length}, trees ${trees.length}`);
console.log(`data.js ${kb('data.js')} KB, model.js ${kb('model.js')} KB, assets.js ${kb('assets.js')} KB`);
