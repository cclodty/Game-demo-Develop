// The asset catalogue: every character, weapon, prop, environment piece,
// landmark and tiling material the game wants as a real model, with its size,
// budgets and the prompts used to make it. One source of truth for three uses:
//
//   1. the game: props and characters with a model in assets/models/ replace
//      their block versions (src/models.js); everything else keeps the blocks
//   2. production: `npm run assets -- docs` writes assets/PROMPTS.md (copy-ready
//      prompts), assets/asset-list.json / .csv (an engine-neutral list) and
//      assets/maps/*.json (the map layouts)
//   3. a later engine move: the JSON files and the masters in assets/source/
//      carry everything another engine needs (see assets/SPEC.md)
//
// Conventions (glTF): metres, Y up, the model's front faces +Z.
//
//   kind      character | weapon | prop | env | landmark | material
//               prop      — placed by the game today (map boxes, barrels, pans)
//               weapon    — held by the characters, lying on pads, in flight
//               env, landmark, material — listed for production; the game
//               takes them in once they exist
//   group     section in PROMPTS.md (see GROUPS)
//   zh        Chinese name
//   priority  1 = do first (many copies or always on screen) … 3 = nice to have
//   uses      copies per map (rooftop, club, docks, senado)
//   size      [width x, depth z, height y] in metres: the size to model it at
//   fit       how the game fits a prop to its map box:
//               'box'        stretch to fill it (crates, barrels)
//               'footprint'  fill width and depth, keep proportions in height
//                            (things with parts above the box: stalls, cars)
//               'height'     uniform scale to the box height (thin things
//                            whose box is only for collision: lamp posts)
//               'tile'       repeat the model along the box's long side, one
//                            copy per `module` metres (long bars, barriers)
//   offset    [x, z, y] shift of the box centre from the object's origin
//   tris      triangle budget of the web game version (scripts/assets.mjs
//             simplifies to it); texture: its largest texture side
//   master    [triangles, texture px] for the high-quality master; defaults by
//             kind in MASTER
//   sockets   weapons: helper points [x, y, z] from the origin (the main grip)
//   anims     clips a non-human rig should carry (characters use ANIMS)
//   prompt    English description of the object; scripts/assets.mjs wraps it
//             with the shared art direction and the technical requirements
//   notes     Chinese notes for whoever makes it

